#!/usr/bin/env node
// Bakes the premade building library (packs/premade): for each recipe, generates candidates over
// many seeds, keeps one per distinct shape (size, storeys, roof, L), and picks a spread of them
// from small to large. Each building is stored whole (the building's properties and its
// furniture and yard), so the library doesn't change when the generator does.
//
//   node --experimental-transform-types --import ./web/tools/ts-resolve.mjs web/tools/bake-premade.mjs

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { BuildingLayout, generateBuilding, MapObject, RECIPES } from '../core/src/index.ts'

const here = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.resolve(here, '../../packs/premade')

/** Recipe -> how many, the category it goes in, and the name of one. */
const PLAN = [
  ['house', 8, 'Houses', 'House'],
  ['row', 6, 'Row houses', 'Row house'],
  ['town', 6, 'Town houses', 'Town house'],
  ['apartment', 6, 'Apartments', 'Apartment block'],
  ['shop', 6, 'Shops', 'Shop'],
  ['office', 6, 'Offices', 'Office'],
  ['school', 5, 'Schools', 'School'],
  ['hospital', 4, 'Hospitals', 'Hospital'],
  ['police', 4, 'Police stations', 'Police station'],
  ['fire', 4, 'Fire stations', 'Fire station'],
  ['cityhall', 4, 'City halls', 'City hall'],
]

fs.rmSync(OUT, { recursive: true, force: true })
fs.mkdirSync(path.join(OUT, 'buildings'), { recursive: true })
let total = 0
for (const [recipeId, count, category, name] of PLAN) {
  const recipe = RECIPES[recipeId]
  const seen = new Map()
  for (let seed = 1; seed <= 600 && seen.size < count * 6; seed++) {
    const g = generateBuilding(recipe, seed * 7919)
    const layout = layoutOf(g.props)
    const cells = layout.cells(0).size
    const shape = cells < g.summary.width * g.summary.depth ? 'L' : 'rect'
    const key = `${g.summary.width}x${g.summary.depth}x${g.summary.storeys}:${g.props['roof/style']}:${shape}`
    if (!seen.has(key)) seen.set(key, g)
  }
  // A spread from small to large: sort by floor area x storeys, take evenly spaced picks.
  const all = [...seen.values()].sort((a, b) => size(a) - size(b))
  const picks = Array.from({ length: Math.min(count, all.length) }, (_, i) => all[Math.round((i * (all.length - 1)) / Math.max(1, count - 1))])
  const entries = picks.map((g, i) => {
    const cs = recipe.cellSize
    // Footprint over the building and everything around it (yard, vehicles), in meters.
    const xs = [0, g.summary.width * cs, ...g.children.map((c) => c.x)]
    const zs = [0, g.summary.depth * cs, ...g.children.map((c) => c.z)]
    return {
      id: `${recipeId}_${String.fromCharCode(97 + i)}`,
      name: `${name} ${String.fromCharCode(65 + i)}`,
      category,
      recipe: recipeId,
      seed: g.seed,
      storeys: g.summary.storeys,
      size: [g.summary.width * cs, g.summary.depth * cs],
      bounds: [Math.min(...xs) - 1, Math.min(...zs) - 1, Math.max(...xs) + 1, Math.max(...zs) + 1].map((v) => Math.round(v * 100) / 100),
      props: g.props,
      children: g.children.map((c) => ({ ...c, x: r2(c.x), y: r2(c.y), z: r2(c.z), rotation: r2(c.rotation) })),
    }
  })
  fs.writeFileSync(path.join(OUT, 'buildings', `${recipeId}.json`), JSON.stringify(entries) + '\n')
  total += entries.length
  console.log(`${recipeId}: ${entries.length} (${entries.map((e) => `${e.size.join('x')}x${e.storeys}`).join(', ')})`)
}
fs.writeFileSync(path.join(OUT, 'pack.json'), JSON.stringify({
  id: 'premade', name: 'Premade buildings', version: '1.0',
  attribution: {
    author: 'Pixel Arena (generated from Kenney, KayKit and styloo CC0 models)',
    source_url: 'https://kenney.nl', license: 'CC0-1.0', license_url: 'https://creativecommons.org/publicdomain/zero/1.0/',
  },
}, null, '\t') + '\n')
fs.writeFileSync(path.join(OUT, 'LICENSE.txt'), 'Premade buildings generated by Pixel Arena from CC0 models (Kenney, KayKit, styloo).\nReleased under CC0 1.0: https://creativecommons.org/publicdomain/zero/1.0/\n')
console.log(`${total} buildings`)

function layoutOf(props) {
  const obj = new MapObject('b', 'building')
  for (const [k, v] of Object.entries(props)) obj.props.set(k, v)
  return BuildingLayout.fromObject(obj)
}

function size(g) {
  return g.summary.width * g.summary.depth * g.summary.storeys
}

function r2(v) {
  return Math.round(v * 1000) / 1000
}
